CREATE DATABASE IF NOT EXISTS cityverse_ai CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE cityverse_ai;

CREATE TABLE IF NOT EXISTS roles (
  id BIGINT AUTO_INCREMENT PRIMARY KEY,
  name VARCHAR(40) NOT NULL UNIQUE,
  description VARCHAR(255) NOT NULL
);

CREATE TABLE IF NOT EXISTS users (
  id BIGINT AUTO_INCREMENT PRIMARY KEY,
  full_name VARCHAR(120) NOT NULL,
  email VARCHAR(160) NOT NULL UNIQUE,
  password_hash VARCHAR(255) NOT NULL,
  role_id BIGINT NOT NULL,
  department VARCHAR(120) DEFAULT 'Citizen Services',
  zone_preference VARCHAR(20) DEFAULT 'CHN-01',
  status ENUM('ACTIVE', 'SUSPENDED') NOT NULL DEFAULT 'ACTIVE',
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  CONSTRAINT fk_users_role FOREIGN KEY (role_id) REFERENCES roles(id)
);

CREATE TABLE IF NOT EXISTS cities (
  id BIGINT AUTO_INCREMENT PRIMARY KEY,
  country VARCHAR(80) NOT NULL,
  state VARCHAR(80) NOT NULL,
  name VARCHAR(120) NOT NULL UNIQUE,
  latitude DECIMAL(9,6) NOT NULL,
  longitude DECIMAL(9,6) NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS city_zones (
  id BIGINT AUTO_INCREMENT PRIMARY KEY,
  city_id BIGINT NOT NULL DEFAULT 1,
  code VARCHAR(20) NOT NULL UNIQUE,
  name VARCHAR(120) NOT NULL,
  area_name VARCHAR(160) NOT NULL DEFAULT '',
  zone_type ENUM('RESIDENTIAL', 'COMMERCIAL', 'INDUSTRIAL', 'CIVIC', 'MIXED') NOT NULL,
  population INT NOT NULL,
  area_sq_km DECIMAL(8,2) NOT NULL,
  latitude DECIMAL(9,6) NOT NULL DEFAULT 13.082700,
  longitude DECIMAL(9,6) NOT NULL DEFAULT 80.270700,
  infrastructure_details TEXT NULL,
  health_score DECIMAL(5,2) NOT NULL DEFAULT 85.00,
  grid_x INT NOT NULL,
  grid_y INT NOT NULL,
  status ENUM('OPTIMAL', 'ADVISORY', 'WARNING', 'CRITICAL') NOT NULL DEFAULT 'OPTIMAL',
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  CONSTRAINT fk_zone_city FOREIGN KEY (city_id) REFERENCES cities(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS infrastructure (
  id BIGINT AUTO_INCREMENT PRIMARY KEY,
  zone_id BIGINT NOT NULL,
  name VARCHAR(160) NOT NULL,
  asset_type ENUM('ROAD', 'HOSPITAL', 'SCHOOL', 'SUBSTATION', 'WATER_PLANT', 'TRANSIT_HUB', 'BUILDING') NOT NULL,
  status ENUM('OPERATIONAL', 'DEGRADED', 'MAINTENANCE', 'CRITICAL') NOT NULL DEFAULT 'OPERATIONAL',
  capacity_pct DECIMAL(5,2) NOT NULL DEFAULT 100.00,
  load_pct DECIMAL(5,2) NOT NULL DEFAULT 50.00,
  latitude DECIMAL(9,6) NOT NULL,
  longitude DECIMAL(9,6) NOT NULL,
  last_inspected_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  CONSTRAINT fk_infra_zone FOREIGN KEY (zone_id) REFERENCES city_zones(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS traffic_data (
  id BIGINT AUTO_INCREMENT PRIMARY KEY,
  city_id BIGINT NOT NULL DEFAULT 1,
  zone_id BIGINT NOT NULL,
  corridor_name VARCHAR(160) NOT NULL,
  vehicle_count INT NOT NULL,
  avg_speed_kmh DECIMAL(5,2) NOT NULL,
  congestion_index DECIMAL(5,2) NOT NULL,
  congestion_level ENUM('LOW', 'MODERATE', 'HIGH', 'SEVERE') NOT NULL,
  traffic_density VARCHAR(32) NOT NULL DEFAULT 'MODERATE',
  road_capacity INT NOT NULL DEFAULT 5000,
  accident_count INT NOT NULL DEFAULT 0,
  weather_condition VARCHAR(64) NOT NULL DEFAULT 'Clear',
  suggested_reroute VARCHAR(255) NOT NULL,
  is_simulated BOOLEAN NOT NULL DEFAULT TRUE,
  recorded_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_traffic_zone FOREIGN KEY (zone_id) REFERENCES city_zones(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS environmental_data (
  id BIGINT AUTO_INCREMENT PRIMARY KEY,
  zone_id BIGINT NOT NULL,
  aqi INT NOT NULL,
  pm25 DECIMAL(6,2) NOT NULL,
  pm10 DECIMAL(6,2) NOT NULL DEFAULT 35.00,
  water_quality_index DECIMAL(5,2) NOT NULL,
  noise_db DECIMAL(5,2) NOT NULL,
  co2_level DECIMAL(6,2) NOT NULL DEFAULT 410.00,
  temperature_c DECIMAL(5,2) NOT NULL,
  humidity_pct INT NOT NULL,
  pollution_level ENUM('GOOD', 'MODERATE', 'UNHEALTHY', 'HAZARDOUS') NOT NULL,
  is_simulated BOOLEAN NOT NULL DEFAULT TRUE,
  recorded_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_env_zone FOREIGN KEY (zone_id) REFERENCES city_zones(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS energy_data (
  id BIGINT AUTO_INCREMENT PRIMARY KEY,
  zone_id BIGINT NOT NULL,
  consumption_mwh DECIMAL(10,2) NOT NULL,
  renewable_energy_mwh DECIMAL(10,2) NOT NULL DEFAULT 0.00,
  non_renewable_energy_mwh DECIMAL(10,2) NOT NULL DEFAULT 0.00,
  renewable_pct DECIMAL(5,2) NOT NULL,
  peak_demand_mw DECIMAL(8,2) NOT NULL,
  grid_load_pct DECIMAL(5,2) NOT NULL,
  street_light_count INT NOT NULL DEFAULT 1500,
  active_street_lights INT NOT NULL DEFAULT 1450,
  power_outages INT NOT NULL DEFAULT 0,
  period_type ENUM('DAILY', 'WEEKLY', 'MONTHLY') NOT NULL DEFAULT 'DAILY',
  is_simulated BOOLEAN NOT NULL DEFAULT TRUE,
  recorded_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_energy_zone FOREIGN KEY (zone_id) REFERENCES city_zones(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS water_data (
  id BIGINT AUTO_INCREMENT PRIMARY KEY,
  zone_id BIGINT NOT NULL,
  total_supply_ml DECIMAL(10,2) NOT NULL DEFAULT 50.00,
  consumption_ml DECIMAL(10,2) NOT NULL,
  reservoir_pct DECIMAL(5,2) NOT NULL,
  water_quality_index DECIMAL(5,2) NOT NULL DEFAULT 90.00,
  supply_pressure_bar DECIMAL(5,2) NOT NULL,
  leakage_pct DECIMAL(5,2) NOT NULL,
  leakage_status VARCHAR(32) NOT NULL DEFAULT 'NORMAL',
  rainfall_mm DECIMAL(6,2) NOT NULL DEFAULT 0.00,
  period_type ENUM('DAILY', 'WEEKLY', 'MONTHLY') NOT NULL DEFAULT 'DAILY',
  is_simulated BOOLEAN NOT NULL DEFAULT TRUE,
  recorded_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_water_zone FOREIGN KEY (zone_id) REFERENCES city_zones(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS ai_agents (
  id BIGINT AUTO_INCREMENT PRIMARY KEY,
  agent_key VARCHAR(64) NOT NULL UNIQUE,
  name VARCHAR(120) NOT NULL,
  domain VARCHAR(120) NOT NULL,
  status ENUM('ACTIVE', 'MONITORING', 'ALERTING', 'IDLE') NOT NULL DEFAULT 'ACTIVE',
  last_run_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  findings_count INT NOT NULL DEFAULT 0,
  confidence_score DECIMAL(4,2) NOT NULL DEFAULT 0.92,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS agent_activities (
  id BIGINT AUTO_INCREMENT PRIMARY KEY,
  agent_id BIGINT NOT NULL,
  zone_id BIGINT NULL,
  severity ENUM('INFO', 'WARNING', 'HIGH', 'CRITICAL') NOT NULL,
  detected_issue VARCHAR(255) NOT NULL,
  analysis_summary TEXT NOT NULL,
  recommendation TEXT NOT NULL,
  coordinated_batch_id VARCHAR(64) NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_activity_agent FOREIGN KEY (agent_id) REFERENCES ai_agents(id) ON DELETE CASCADE,
  CONSTRAINT fk_activity_zone FOREIGN KEY (zone_id) REFERENCES city_zones(id) ON DELETE SET NULL
);

CREATE TABLE IF NOT EXISTS predictions (
  id BIGINT AUTO_INCREMENT PRIMARY KEY,
  zone_id BIGINT NOT NULL,
  domain ENUM('TRAFFIC', 'AIR_POLLUTION', 'ENERGY', 'WATER_DEMAND') NOT NULL,
  model_type VARCHAR(64) NOT NULL DEFAULT 'LINEAR_TREND_SIMULATED',
  horizon_hours INT NOT NULL DEFAULT 24,
  current_value DECIMAL(10,2) NOT NULL,
  predicted_value DECIMAL(10,2) NOT NULL,
  unit VARCHAR(32) NOT NULL,
  risk_level ENUM('LOW', 'MEDIUM', 'HIGH', 'CRITICAL') NOT NULL,
  confidence_pct DECIMAL(5,2) NOT NULL,
  is_simulated BOOLEAN NOT NULL DEFAULT TRUE,
  forecast_series_json JSON NOT NULL,
  generated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_pred_zone FOREIGN KEY (zone_id) REFERENCES city_zones(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS emergency_incidents (
  id BIGINT AUTO_INCREMENT PRIMARY KEY,
  zone_id BIGINT NOT NULL,
  reported_by_user_id BIGINT NULL,
  reported_by_name VARCHAR(120) NULL,
  title VARCHAR(180) NOT NULL,
  category ENUM('FIRE', 'ROAD_ACCIDENT', 'FLOOD', 'FLOOD_WARNING', 'WATER_LEAKAGE', 'POWER_FAILURE', 'ENVIRONMENTAL_ALERT', 'INFRASTRUCTURE_FAILURE', 'OTHER') NOT NULL,
  priority ENUM('LOW', 'MEDIUM', 'HIGH', 'CRITICAL') NOT NULL,
  status ENUM('OPEN', 'DISPATCHED', 'IN_PROGRESS', 'RESOLVED') NOT NULL DEFAULT 'OPEN',
  location_detail VARCHAR(255) NOT NULL,
  latitude DECIMAL(9,6) NOT NULL DEFAULT 13.082700,
  longitude DECIMAL(9,6) NOT NULL DEFAULT 80.270700,
  description TEXT NULL,
  response_recommendation TEXT NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  CONSTRAINT fk_inc_zone FOREIGN KEY (zone_id) REFERENCES city_zones(id) ON DELETE CASCADE,
  CONSTRAINT fk_inc_user FOREIGN KEY (reported_by_user_id) REFERENCES users(id) ON DELETE SET NULL
);

CREATE TABLE IF NOT EXISTS notifications (
  id BIGINT AUTO_INCREMENT PRIMARY KEY,
  zone_id BIGINT NULL,
  title VARCHAR(160) NOT NULL,
  message TEXT NOT NULL,
  severity ENUM('INFO', 'WARNING', 'CRITICAL') NOT NULL,
  category VARCHAR(64) NOT NULL,
  is_read BOOLEAN NOT NULL DEFAULT FALSE,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_notif_zone FOREIGN KEY (zone_id) REFERENCES city_zones(id) ON DELETE SET NULL
);

CREATE TABLE IF NOT EXISTS ai_recommendations (
  id BIGINT AUTO_INCREMENT PRIMARY KEY,
  batch_id VARCHAR(64) NOT NULL UNIQUE,
  summary TEXT NOT NULL,
  priority_actions_json JSON NOT NULL,
  contributing_agents_json JSON NOT NULL,
  status ENUM('PENDING', 'ACKNOWLEDGED', 'APPLIED') NOT NULL DEFAULT 'PENDING',
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
